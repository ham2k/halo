// What the ADIF import picker asks for, and what it accepts back.

import 'dart:convert';
import 'dart:typed_data';

import 'package:flutter/foundation.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:ham2k_logger/views/operation/adif_import_flow.dart';

Uint8List _bytes(String text) => Uint8List.fromList(latin1.encode(text));

void main() {
  group('the picker filter', () {
    tearDown(() => debugDefaultTargetPlatformOverride = null);

    test('Android asks for no filter at all', () {
      debugDefaultTargetPlatformOverride = TargetPlatform.android;
      // A group carrying extensions or MIME types greys `.adi` out of the
      // Android picker entirely — nothing in the browser is selectable.
      expect(adifTypeGroups(), isEmpty);
    });

    test('other platforms filter to ADIF', () {
      debugDefaultTargetPlatformOverride = TargetPlatform.macOS;
      final groups = adifTypeGroups();
      expect(groups.single.extensions, containsAll(['adi', 'adif']));
      // iOS throws for a group with extensions but no UTIs.
      expect(groups.single.uniformTypeIdentifiers, isNotEmpty);
    });
  });

  group('recognising ADIF by its bytes', () {
    test('a file the Android picker renamed is still recognised', () {
      // The whole point: Android hands back `mylog.bin`, so the NAME says no
      // and only the bytes can say yes.
      expect(looksLikeAdif('mylog.bin'), isFalse);
      expect(bytesLookLikeAdif(_bytes('Generated by HaLo\n<EOH>\n<CALL:5>N0DEV<EOR>\n')), isTrue);
    });

    test('a header-less file of bare records is ADIF too', () {
      expect(bytesLookLikeAdif(_bytes('<call:5>N0DEV <band:3>20m <eor>')), isTrue);
    });

    test('prose and markup are not ADIF', () {
      // `<[a-z_]+>` alone would call every HTML file an ADIF log, and the
      // refusal dialog is the only thing standing between a mis-tap and a
      // full parse of whatever was picked.
      expect(bytesLookLikeAdif(_bytes('<html><body>hello</body></html>')), isFalse);
      expect(bytesLookLikeAdif(_bytes('Dear operator, the contest is on Saturday.')), isFalse);
    });

    test('undecodable bytes are refused, not thrown at', () {
      // A JPEG reaching the sniff must come back false — a decoder that throws
      // would surface as an import failure instead of a plain refusal.
      expect(bytesLookLikeAdif(Uint8List.fromList([0xFF, 0xD8, 0xFF, 0xE0, 0x00, 0x10])), isFalse);
    });
  });
}
