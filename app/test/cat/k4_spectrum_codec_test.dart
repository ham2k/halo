import 'dart:io';
import 'dart:typed_data';

import 'package:flutter_test/flutter_test.dart';
import 'package:ham2k_logger/services/cat/drivers/k4_spectrum_codec.dart';

// Synthetic format fixtures, not hardware captures. Their checksum builder
// uses an MSB-first calculation with explicit reflection, independently of
// the decoder's reflected, right-shifting implementation.
int _reflect(int value, int bits) {
  var result = 0;
  for (var bit = 0; bit < bits; bit++) {
    result = (result << 1) | ((value >> bit) & 1);
  }
  return result;
}

int _fixtureCrc(Iterable<int> bytes) {
  var crc = 0xffff;
  for (final byte in bytes) {
    crc ^= _reflect(byte, 8) << 8;
    for (var bit = 0; bit < 8; bit++) {
      crc = ((crc << 1) ^ (crc & 0x8000 != 0 ? 0x1021 : 0)) & 0xffff;
    }
  }
  return _reflect(crc, 16) ^ 0xffff;
}

void _seal(Uint8List bytes) {
  bytes[63] = 0;
  bytes[63] = (-bytes.take(63).fold<int>(0, (sum, byte) => sum + byte)) & 0xff;
  ByteData.sublistView(bytes).setUint16(4160, _fixtureCrc(bytes.take(4160)), Endian.big);
}

Uint8List _packet({
  int sequence = 17,
  String pan = 'A',
  int version = 2,
  String rate = '192000',
  String center = '00014074000',
  String noise = '-1234',
  List<int> levels = const [],
}) {
  final bytes = Uint8List(4162);
  bytes.setRange(0, 7, [0xff, 0xfe, 0x01, 0x00, version, sequence, pan.codeUnitAt(0)]);
  bytes.setRange(7, 13, rate.codeUnits);
  bytes.setRange(13, 24, center.codeUnits);
  bytes.setRange(24, 29, noise.codeUnits);
  final data = ByteData.sublistView(bytes);
  for (var i = 0; i < 2048; i++) {
    data.setInt16(64 + 2 * i, i < levels.length ? levels[i] : -1200, Endian.big);
  }
  _seal(bytes);
  return bytes;
}

Uint8List _joined(Iterable<List<int>> chunks) => Uint8List.fromList([for (final chunk in chunks) ...chunk]);

void main() {
  test('CRC matches the independent X-25 check value', () {
    final check = Uint8List.fromList('123456789'.codeUnits);
    expect(k4SpectrumCrc16(check), 0x906e);
    expect(_fixtureCrc(check), 0x906e);
    expect(k4SpectrumCrc16(Uint8List(0)), 0);
  });

  test('physical K4 captures preserve all four pans and span-dependent sample rates', () {
    // Unmodified capture bytes. Expected values were read with Python struct
    // and binascii, not generated by the decoder or synthetic fixture builder.
    final original = File('test/cat/fixtures/k4-spectrum/k4-lan-9201-ayb.bin').readAsBytesSync();
    final spans = File('test/cat/fixtures/k4-spectrum/k4-lan-9201-spans-aybz.bin').readAsBytesSync();
    expect(original, hasLength(12486));
    expect(spans, hasLength(20810));
    final bytes = _joined([original, spans]);
    final expected = [
      (
        sequence: 12,
        pan: 'A',
        rate: 96000,
        center: 14045000,
        noise: -131.6,
        crc: 0xcb08,
        bins: [-172.5, -172.5, -169.5, -134.9, -136.0, -133.1, -136.7, -127.4, -169.5],
      ),
      (sequence: 12, pan: 'Y', rate: 3000, center: 14047440, noise: 8.7, crc: 0x2141, bins: [-1.8, -1.8, -1.8, 6.3, 11.8, 5.2, -8.7, 5.2, 1.3]),
      (
        sequence: 11,
        pan: 'B',
        rate: 96000,
        center: 7045000,
        noise: -121.5,
        crc: 0xd732,
        bins: [-154.5, -154.5, -154.5, -124.8, -124.6, -115.2, -119.2, -119.1, -151.5],
      ),
      (
        sequence: 45,
        pan: 'A',
        rate: 24000,
        center: 14036950,
        noise: -139.2,
        crc: 0xa34f,
        bins: [-166.5, -155.4, -153.5, -143.1, -139.9, -137.9, -142.4, -132.6, -159.6],
      ),
      (sequence: 45, pan: 'Y', rate: 3000, center: 14037360, noise: 14.7, crc: 0xcc19, bins: [-8.7, -8.7, -8.7, -0.6, -0.1, 2.5, 6.1, 10.4, -7.8]),
      (
        sequence: 44,
        pan: 'B',
        rate: 96000,
        center: 14045000,
        noise: -110.1,
        crc: 0x7de1,
        bins: [-154.5, -151.5, -154.5, -112.6, -113.8, -128.1, -112.8, -113.1, -154.5],
      ),
      (sequence: 43, pan: 'Z', rate: 3000, center: 14037360, noise: 10.7, crc: 0x6887, bins: [-7.7, -7.7, -7.7, -10.7, 0.4, 3.2, 4.9, 10.9, -7.7]),
      (
        sequence: 55,
        pan: 'A',
        rate: 48000,
        center: 14036950,
        noise: -134.0,
        crc: 0x38fc,
        bins: [-178.5, -178.5, -178.5, -147.8, -136.0, -138.8, -134.8, -142.3, -178.5],
      ),
    ];
    final decoder = K4SpectrumDecoder();
    final packets = <K4SpectrumPacket>[];
    for (var offset = 0; offset < bytes.length; offset += 257) {
      final end = offset + 257 < bytes.length ? offset + 257 : bytes.length;
      packets.addAll(decoder.add(Uint8List.sublistView(bytes, offset, end)));
    }
    expect(packets, hasLength(expected.length));
    const indices = [0, 1, 2, 127, 511, 1023, 1024, 1535, 2047];
    for (var i = 0; i < expected.length; i++) {
      final packet = packets[i], want = expected[i];
      final raw = Uint8List.sublistView(bytes, i * 4162, (i + 1) * 4162);
      expect(ByteData.sublistView(raw).getUint16(4160, Endian.big), want.crc);
      expect(k4SpectrumCrc16(Uint8List.sublistView(raw, 0, 4160)), want.crc);
      expect(packet.sequence, want.sequence);
      expect(packet.panId, want.pan);
      expect(packet.sampleRateHz, want.rate);
      expect(packet.centerHz, want.center);
      expect(packet.noiseFloorDb, want.noise);
      expect(packet.headerBytes, raw.take(64).toList());
      for (var j = 0; j < indices.length; j++) {
        expect(packet.levels[indices[j]], closeTo(want.bins[j], 0.00002), reason: '${want.pan} bin ${indices[j]}');
      }
    }
    expect(decoder.pendingBytes, 0);
    expect(decoder.diagnostics.framesDecoded, expected.length);
    expect(decoder.diagnostics.discardedBytes, 0);
    expect(decoder.diagnostics.invalidHeaders, 0);
    expect(decoder.diagnostics.invalidPayloadChecksums, 0);
    expect(decoder.diagnostics.unsupportedVersions, 0);
    expect(decoder.diagnostics.unsupportedPanIds, 0);
  });

  test('preserves wire metadata and signed big-endian tenths without calibration', () {
    final bytes = _packet(levels: [-32768, -1234, -1, 0, 1, 1234, 32767]);
    bytes.setRange(29, 63, List.generate(34, (i) => i * 7));
    _seal(bytes);
    final decoder = K4SpectrumDecoder();
    final packet = decoder.add(bytes).single;
    expect(packet.sequence, 17);
    expect(packet.panId, 'A');
    expect(packet.sampleRateHz, 192000);
    expect(packet.centerHz, 14074000);
    expect(packet.noiseFloorDb, -123.4);
    expect(packet.levels, hasLength(2048));
    for (final (i, expected) in [-3276.8, -123.4, -0.1, 0.0, 0.1, 123.4, 3276.7].indexed) {
      expect(packet.levels[i], closeTo(expected, 0.0002));
    }
    expect(packet.levels.last, -120);
    expect(packet.headerBytes, bytes.take(64).toList());
    expect(decoder.pendingBytes, 0);
    expect(decoder.diagnostics.framesDecoded, 1);
    expect(decoder.diagnostics.discardedBytes, 0);

    // Decoder reuse and caller mutation must not rewrite a captured packet.
    bytes.fillRange(0, bytes.length, 0);
    decoder.add(_packet(sequence: 18, levels: [100]));
    expect(packet.headerBytes[5], 17);
    expect(packet.levels.first, closeTo(-3276.8, 0.0002));
    expect(() => packet.headerBytes[0] = 0, throwsUnsupportedError);
    expect(() => packet.levels[0] = 0, throwsUnsupportedError);
  });

  test('accepts fixed-width ASCII padding and signs without a sample-rate whitelist', () {
    final packets = K4SpectrumDecoder().add(
      _joined([
        _packet(rate: ' +9600', center: ' +14074000 ', noise: ' -123'),
        _packet(rate: '999999', center: '00000000000', noise: '+0012'),
        _packet(rate: '12000 ', center: '14074000   ', noise: '123  '),
      ]),
    );
    expect(packets.map((packet) => packet.sampleRateHz), [9600, 999999, 12000]);
    expect(packets.map((packet) => packet.centerHz), [14074000, 0, 14074000]);
    expect(packets.map((packet) => packet.noiseFloorDb), [-12.3, 1.2, 12.3]);
  });

  test('TCP chunk boundaries have no meaning, including inside sync and footer', () {
    final bytes = _packet();
    for (final split in {...List.generate(65, (i) => i), 65, 127, 2048, 4159, 4160, 4161}) {
      final decoder = K4SpectrumDecoder();
      expect(decoder.add(Uint8List.sublistView(bytes, 0, split)), isEmpty, reason: 'split $split');
      expect(decoder.add(Uint8List.sublistView(bytes, split)).single.sequence, 17, reason: 'split $split');
      expect(decoder.pendingBytes, 0);
    }
    final decoder = K4SpectrumDecoder();
    final packets = <K4SpectrumPacket>[];
    for (var i = 0; i < bytes.length; i++) {
      packets.addAll(decoder.add(Uint8List.sublistView(bytes, i, i + 1)));
    }
    expect(packets, hasLength(1));
    expect(decoder.diagnostics.discardedBytes, 0);
  });

  test('coalesced packets retain every pan, repeated sequence and wraparound', () {
    final decoder = K4SpectrumDecoder();
    final packets = decoder.add(
      _joined([_packet(sequence: 255, pan: 'A'), _packet(sequence: 0, pan: 'B'), _packet(sequence: 0, pan: 'Y'), _packet(sequence: 17, pan: 'Z')]),
    );
    expect(packets.map((packet) => packet.sequence), [255, 0, 0, 17]);
    expect(packets.map((packet) => packet.panId), ['A', 'B', 'Y', 'Z']);
    expect(decoder.diagnostics.framesDecoded, 4);
    expect(decoder.pendingBytes, 0);
  });

  test('large garbage input retains only a possible sync suffix', () {
    final decoder = K4SpectrumDecoder();
    final garbage = Uint8List(1000000)..fillRange(0, 1000000, 0xff);
    expect(
      decoder.add(
        _joined([
          garbage,
          [0xff, 0xfe, 0x01],
        ]),
      ),
      isEmpty,
    );
    expect(decoder.pendingBytes, 3);
    expect(decoder.diagnostics.discardedBytes, garbage.length);
    expect(decoder.add(Uint8List.sublistView(_packet(), 3)), hasLength(1));
    expect(decoder.pendingBytes, 0);
    expect(decoder.diagnostics.framesDecoded, 1);
  });

  test('a valid sync inside a corrupted candidate is not discarded with that candidate', () {
    // The first sender lost most of its payload. The next header is inside
    // the 4162 bytes the decoder would otherwise consume as one bad packet.
    final stream = _joined([_packet().sublist(0, 101), _packet(sequence: 44)]);
    final decoder = K4SpectrumDecoder();
    final packets = decoder.add(stream);
    expect(packets.map((packet) => packet.sequence), [44]);
    expect(decoder.diagnostics.invalidPayloadChecksums, 1);
    expect(decoder.diagnostics.discardedBytes, 101);
    expect(decoder.pendingBytes, 0);
  });

  test('header and payload integrity failures have distinct diagnostics and recover', () {
    final badHeader = _packet()..[30] = 1;
    final badPayload = _packet()..[100] ^= 1;
    final decoder = K4SpectrumDecoder();
    expect(decoder.add(_joined([badHeader, badPayload, _packet(sequence: 99)])).single.sequence, 99);
    expect(decoder.diagnostics.invalidHeaders, 1);
    expect(decoder.diagnostics.invalidPayloadChecksums, 1);
    expect(decoder.diagnostics.discardedBytes, 4162 * 2);
  });

  test('the CRC footer is big-endian even though CRC calculation reflects bits', () {
    final bytes = _packet();
    expect(bytes[4160], isNot(bytes[4161]));
    final high = bytes[4160];
    bytes[4160] = bytes[4161];
    bytes[4161] = high;
    final decoder = K4SpectrumDecoder();
    expect(decoder.add(_joined([bytes, _packet(sequence: 32)])).single.sequence, 32);
    expect(decoder.diagnostics.invalidPayloadChecksums, 1);
  });

  test('unknown versions and pan IDs are rejected rather than interpreted as defaults', () {
    final decoder = K4SpectrumDecoder();
    expect(decoder.add(_joined([_packet(version: 3), _packet(pan: 'C'), _packet(pan: 'B')])).single.panId, 'B');
    expect(decoder.diagnostics.unsupportedVersions, 1);
    expect(decoder.diagnostics.unsupportedPanIds, 1);
    expect(decoder.diagnostics.invalidHeaders, 0);
    expect(decoder.diagnostics.discardedBytes, 4162 * 2);
  });

  test('malformed metadata never substitutes a plausible frequency, rate or noise floor', () {
    final malformed = [
      _packet(rate: '000000'),
      _packet(rate: '-00001'),
      _packet(rate: '12.345'),
      _packet(rate: ' 12 34'),
      _packet(rate: '      '),
      _packet(rate: '\t12000'),
      _packet(rate: '12000\n'),
      _packet(center: '-0000000001'),
      _packet(center: '00014074e00'),
      _packet(noise: '1.234'),
      _packet(noise: '-12\u00004'),
    ];
    final decoder = K4SpectrumDecoder();
    expect(decoder.add(_joined([...malformed, _packet(sequence: 82)])).single.sequence, 82);
    expect(decoder.diagnostics.invalidHeaders, malformed.length);
    expect(decoder.diagnostics.discardedBytes, 4162 * malformed.length);
  });

  test('a partial stream is bounded and reset cannot attach its tail to a new session', () {
    final decoder = K4SpectrumDecoder();
    expect(decoder.add(_joined([_packet(version: 1), _packet().sublist(0, 4161)])), isEmpty);
    expect(decoder.pendingBytes, 4161);
    final before = decoder.diagnostics;
    decoder.reset();
    expect(decoder.pendingBytes, 0);
    expect(decoder.diagnostics.framesDecoded, 0);
    expect(decoder.diagnostics.discardedBytes, 0);
    expect(decoder.diagnostics.invalidHeaders, 0);
    expect(decoder.diagnostics.invalidPayloadChecksums, 0);
    expect(decoder.diagnostics.unsupportedVersions, 0);
    expect(decoder.diagnostics.unsupportedPanIds, 0);
    expect(before.unsupportedVersions, 1, reason: 'diagnostics are a stable snapshot');
    expect(decoder.add(_packet(sequence: 6)).single.sequence, 6);
  });
}
