// Regenerates test/golden/schema.sql — the committed snapshot of what a fresh
// install's schema looks like.
//
// The snapshot exists because every migration fixture is derived from the
// current table declarations, which makes one whole class of mistake invisible
// to those tests: add a column or an index without bumping `schemaVersion` and
// the fixture gets it for free, so the upgrade tests still pass while real
// installs never receive it. A committed artifact is not a re-derivation, so
// it notices.
//
// Run after a DELIBERATE schema change, and treat the diff as the moment to
// ask whether `schemaVersion` and a migration step are owed:
//
//   cd packages/halo_core && dart run tool/dump_schema.dart

import 'dart:io';

import 'package:drift/native.dart';
import 'package:halo_core/halo_core.dart';

Future<void> main() async {
  final db = HaLoDatabase(NativeDatabase.memory());
  final rows = await db
      .customSelect(
        "SELECT sql FROM sqlite_master "
        "WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY name",
      )
      .get();
  final schema =
      rows.map((r) => r.read<String>('sql').replaceAll(RegExp(r'\s+'), ' ').trim()).toList();
  await db.close();

  final out = File('test/golden/schema.sql');
  out.parent.createSync(recursive: true);
  out.writeAsStringSync([
    '-- Generated by tool/dump_schema.dart — do not hand-edit.',
    '-- A change here means the storage schema changed: check whether',
    '-- HaLoDatabase.schemaVersion and a migration step are owed with it.',
    ...schema,
    '',
  ].join('\n'));

  stdout.writeln('wrote ${out.path} (${schema.length} entities)');
}
