// ARRL and RAC sections — the exchange ARRL Field Day asks for.
//
// DUPLICATED, on purpose. `wfd` carries its own copy of this file and of
// the scorer beside it. The two contests are near-identical and a factory would
// express that, but each extension is meant to stand alone — to be read, moved
// and distributed without reaching into a sibling — and that is worth more here
// than not repeating the table. app-polo's `wfd` imports app-polo's `fd` for
// exactly this data; the copy is the deliberate divergence.
//
// INLINE DATA. A scorer is synchronous and a host call is not
// (docs/design/contests.md §5.3), so a section table living behind
// `dbLookupSelectAll` could not be read while folding a log.
//
// PROVENANCE, stated exactly: the data is app-polo's, transformed mechanically
// rather than retyped, and every entry was checked back against that source. It
// has NOT been checked against the ARRL's own published list — an earlier
// version of this comment claimed it had, which was wrong and is the sort of
// claim that stops the next reader looking.
//
// One correction against app-polo, on Sebastian's reading of the rules: it
// lists `YT` as a RAC section, which RAC has indeed added — but FIELD DAY still
// counts Yukon inside `TER`, so YT is not a valid exchange here and is not
// listed. 14 RAC sections, not 15.

